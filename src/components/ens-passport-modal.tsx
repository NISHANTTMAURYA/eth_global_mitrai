'use client';
import { useState } from 'react';
import { Modal } from './ui';
import { getCharacterEnsPassport, type EnsPassport } from '@/lib/ens';
import type { Character } from '@/lib/domain';
import { Globe, Copy, Check, Database, Clock, Fingerprint } from 'lucide-react';

export default function EnsPassportModal({
  character,
  close,
}: {
  character: Character;
  close: () => void;
}) {
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const passport = getCharacterEnsPassport(character);

  const handleCopy = (text: string, key: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  return (
    <Modal title="ENS name preview" close={close}>
      <div className="ens-passport-container">
        <div className="ens-passport-header">
          <div className="ens-badge-large">
            <Globe size={18} className="ens-icon-glow" />
            <span className="ens-subname-text">{passport.subname}</span>
            <span className="ens-verified-tag">
              Name preview
            </span>
          </div>
          <p className="ens-passport-desc">
            This name and its records are generated by MitrAI. The subname and text records have not been registered on Ethereum ENS.
          </p>
        </div>

        <div className="ens-records-card">
          <div className="ens-card-header">
            <span>Local preview data (not on ENS)</span>
            <button
              className="text-button ens-copy-all"
              onClick={() =>
                handleCopy(
                  JSON.stringify(
                    {
                      name: passport.subname,
                      node: passport.node,
                      records: passport.records,
                    },
                    null,
                    2,
                  ),
                  'all',
                )
              }
            >
              {copiedKey === 'all' ? (
                <>
                  <Check size={12} /> Copied JSON
                </>
              ) : (
                <>
                  <Copy size={12} /> Copy records JSON
                </>
              )}
            </button>
          </div>

          <div className="ens-records-list">
            <div className="ens-record-row">
              <span className="ens-record-key">
                <Fingerprint size={13} />
                <span>namehash (node)</span>
              </span>
              <span className="ens-record-val monospace" title={passport.node}>
                {passport.node.slice(0, 10)}…{passport.node.slice(-8)}
                <button
                  className="icon-copy-btn"
                  onClick={() => handleCopy(passport.node, 'node')}
                  title="Copy node hash"
                >
                  {copiedKey === 'node' ? <Check size={12} /> : <Copy size={12} />}
                </button>
              </span>
            </div>

            <div className="ens-record-row highlight">
              <span className="ens-record-key">
                <Database size={13} />
                <span>arkiv.entity</span>
              </span>
              <span className="ens-record-val monospace" title={passport.records['arkiv.entity']}>
                {passport.records['arkiv.entity'].length > 20
                  ? `${passport.records['arkiv.entity'].slice(0, 14)}…${passport.records['arkiv.entity'].slice(-6)}`
                  : passport.records['arkiv.entity']}
                <button
                  className="icon-copy-btn"
                  onClick={() => handleCopy(passport.records['arkiv.entity'], 'arkiv')}
                  title="Copy Arkiv key"
                >
                  {copiedKey === 'arkiv' ? <Check size={12} /> : <Copy size={12} />}
                </button>
              </span>
            </div>

            <div className="ens-record-row">
              <span className="ens-record-key">
                <Clock size={13} />
                <span>agent.status</span>
              </span>
              <span className="ens-record-val">
                <span className="stage-pill-mini">{passport.records['agent.status']}</span>
                <span className="ens-subval">{passport.records['agent.lifespan']}</span>
              </span>
            </div>

            <div className="ens-record-row">
              <span className="ens-record-key">
                <Globe size={13} />
                <span>agent.guardian</span>
              </span>
              <span className="ens-record-val monospace">
                {passport.records['agent.guardian'].startsWith('0x')
                  ? `${passport.records['agent.guardian'].slice(0, 8)}…${passport.records['agent.guardian'].slice(-6)}`
                  : passport.records['agent.guardian']}
              </span>
            </div>

            <div className="ens-record-row">
              <span className="ens-record-key">
                <span>agent.model</span>
              </span>
              <span className="ens-record-val">{passport.records['agent.model']}</span>
            </div>

            <div className="ens-record-row">
              <span className="ens-record-key">
                <span>description</span>
              </span>
              <span className="ens-record-val text-wrap">{passport.records['description']}</span>
            </div>
          </div>
        </div>

        <div className="ens-passport-actions">
          <button
            className="button primary small-button"
            onClick={() => handleCopy(passport.subname, 'subname')}
          >
            {copiedKey === 'subname' ? (
              <>
                <Check size={14} />
                <span>Copied {passport.subname}</span>
              </>
            ) : (
              <>
                <Copy size={14} />
                <span>Copy Subname</span>
              </>
            )}
          </button>
        </div>
      </div>
    </Modal>
  );
}

